from pathlib import Path
from datetime import datetime, timezone
import argparse
import hashlib
import json
import platform
import shutil
import sys
import zipfile

PROJECT = Path(__file__).resolve().parent
sys.path.insert(0, str(PROJECT / 'src'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, help='New output directory; existing directories are never overwritten')
    parser.add_argument('--check-only', action='store_true', help='Audit the included reference results without fitting models')
    args = parser.parse_args()
    import numpy as np
    import pandas as pd
    import sklearn
    import hourly_models
    import model_stage
    from project_checks import check_inputs, check_results
    inventory, frames = check_inputs(PROJECT)
    if args.check_only:
        audit = check_results(PROJECT, PROJECT / 'reference_results', inventory, frames)
        print(json.dumps(audit, indent=2))
        print('\nREFERENCE RESULT CHECKS PASSED')
        return
    out = args.output or PROJECT / 'results' / ('run_' + datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ'))
    out = out.resolve()
    out.mkdir(parents=True, exist_ok=False)
    try:
        print('Inputs verified. Reproducing six-hour and one-hour models from derived tables.', flush=True)
        model_stage.run(PROJECT / 'data/BDAPP_model_inputs.zip', out / 'six_hour_baselines')
        hourly_models.run(PROJECT / 'data/FinalSpark_hourly_summary.zip', out / 'hourly_models')
        audit = check_results(PROJECT, out, inventory, frames)
        (out / 'project_checks.json').write_text(json.dumps(audit, indent=2), encoding='utf-8')
        pd.DataFrame(inventory).to_csv(out / 'dataset_inventory.csv', index=False)
        external = out / 'external_descriptive_results'
        external.mkdir()
        for name in ['DANDI_summary.zip', 'Zenodo_summary.zip']:
            shutil.copy2(PROJECT / 'data' / name, external / name)
        hourly = pd.read_csv(out / 'hourly_models/hourly_model_comparison.csv')
        primary = hourly[hourly.protocol.eq('FS369_to_FS437_all_hours') & ~hourly.model.str.startswith('ablation_')]
        primary.to_csv(out / 'primary_hourly_results.csv', index=False)
        report = [
            'BDAPP: neural activity analysis and exploratory prediction',
            'Maral Farhatnejad | 23012856', '',
            'RESULT: Age and remaining individual biological lifespan prediction are not validated.',
            'All primary one-hour transfer models have negative R2 on FS437.',
            'Some models improve MAE over the training-median baseline, but transfer remains poor.',
            'Targets are calendar age since Batch Start and time to an activity-defined experiment endpoint.',
            'They are not direct measurements of maturation or independently verified individual deaths.', '',
            'DATA INVENTORY', pd.DataFrame(inventory).to_string(index=False), '',
            'ONE-HOUR MODELS: TRAIN FS369 (509 HOURS), TEST FS437 (115 HOURS)',
            primary[['target', 'model', 'MAE_days', 'R2']].to_string(index=False), '',
            'DANDI: separate descriptive rat-culture sessions; no culture-age or lifespan model.',
            'Zenodo: separate descriptive human forebrain organoids; no per-organoid age/death labels.',
            'Zenodo fs417-org0: 33096 valid times retained; mismatched amplitudes withheld.', '',
            'CHECKS: ' + audit['status'], audit['scope'], '',
            'Results in this directory were generated by this invocation. Software versions are recorded.',
            'Small forest differences across versions/platforms do not establish an improvement.',
            'Read docs/METHODS_AND_LIMITATIONS.md before presenting the results.',
        ]
        (out / 'PROJECT_RESULTS.txt').write_text('\n'.join(report), encoding='utf-8')
        source_paths = [PROJECT / 'run_project.py', *sorted((PROJECT / 'src').glob('*.py'))]
        provenance = dict(created_utc=datetime.now(timezone.utc).isoformat(),
            result_origin='Recomputed in this runtime from user-uploaded derived inputs; no raw FinalSpark recordings opened.',
            software=dict(python=platform.python_version(), numpy=np.__version__, pandas=pd.__version__, sklearn=sklearn.__version__),
            source_sha256={p.relative_to(PROJECT).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in source_paths},
            inputs=json.loads((PROJECT / 'provenance/input_manifest.json').read_text()))
        (out / 'run_provenance.json').write_text(json.dumps(provenance, indent=2), encoding='utf-8')
        bundle = out / 'BDAPP_project_results.zip'
        files = [p for p in sorted(out.rglob('*')) if p.is_file() and p != bundle]
        file_manifest = {p.relative_to(out).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in files}
        (out / 'result_manifest.json').write_text(json.dumps(file_manifest, indent=2), encoding='utf-8')
        with zipfile.ZipFile(bundle, 'w', zipfile.ZIP_DEFLATED) as archive:
            for path in files + [out / 'result_manifest.json']:
                archive.write(path, path.relative_to(out))
        print('\nPROJECT RUN COMPLETE — CHECKS PASSED')
        print('Read:', out / 'PROJECT_RESULTS.txt')
        print('Results ZIP:', bundle)
    except Exception as exc:
        (out / 'RUN_FAILED.txt').write_text(type(exc).__name__ + ': ' + str(exc), encoding='utf-8')
        raise


if __name__ == '__main__':
    main()
